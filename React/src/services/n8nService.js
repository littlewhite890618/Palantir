
const N8N_URL = 'http://localhost:5678';

// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
// 📦 VIBE: getAllSubsidy 是前端的「進貨窗口」
//    SearchPage 和 AllSubsidyPage 都靠它活著，
//    但它們不知道資料從哪裡來、長什麼格式，
//    這個函式把所有的複雜性都吞進去，吐出乾淨的陣列。
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
export const getAllSubsidy = async () => {
  try {

    // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    // 🌐 VIBE: 用 fetch 去敲 n8n 的 webhook 門
    //    GET 方法代表「我只是要資料，我不帶任何東西過來」，
    //    這符合「取得補助案清單」這個純讀取的行為語意。
    // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    const response = await fetch(`${N8N_URL}/webhook/get-all-subsidy`, {
      method: 'GET',
    });

    // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    // 🚨 VIBE: response.ok 是第一道防線
    //    fetch 本身「不會因為 404 或 500 報錯」，它只管網路有沒有通。
    //    所以我們要自己判斷 HTTP 狀態碼是否成功（200-299），
    //    否則 n8n 回傳錯誤訊息，程式還以為一切正常繼續跑下去。
    // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    if (!response.ok) throw new Error('無法取得資料');

    const data = await response.json();

    // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    // 🔧 VIBE: n8n 有時候會多包一層 { json: {...} }，有時候不會
    //    這個判斷是在問：「你給我的是原始陣列，還是被 n8n 包裝過的陣列？」
    //    如果是包裝過的（data[0]?.json 存在），就剝掉外殼只取裡面的資料。
    //    這樣前端的其他地方永遠收到格式一致的乾淨陣列，
    //    不需要每個頁面自己處理 n8n 的格式怪癖。
    // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    if (Array.isArray(data) && data[0]?.json) {
      return data.map(item => item.json);
    }
    return data;

  } catch (error) {

    // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    // 🛡️ VIBE: 出錯了，但不能讓頁面崩潰
    //    回傳空陣列 [] 是一種「優雅的失敗」策略，
    //    讓呼叫這個函式的頁面繼續跑，只是顯示「沒有資料」，
    //    而不是整個畫面爆錯噴給使用者看。
    //    console.error 留給開發者除錯用，使用者不會看到這行。
    // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    console.error('獲取所有資料失敗:', error);
    return [];
  }
};