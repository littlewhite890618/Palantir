// 🧠 VIBE: amount 欄位混著純數字（推測單位萬元，如「40」）跟比例字串（如「補助經費50%」）。
//    顯示時：純數字後面補「萬」→「40萬」（比例型或像「一億」這種特例維持原樣），
//    再一律於最前面加「最高」→「最高 40萬」「最高 補助經費50%」「最高 一億」。
//    ⚠️ 只格式化顯示，不動資料庫原始值，也不影響 HomePage 的金額篩選（getAmountBucket
//    仍讀原始數字），所以篩選邏輯不會因為多了「萬」或「最高」而失效。
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
export function formatAmount(amount) {
  if (!amount) return '';
  const withUnit = /^\d+(\.\d+)?$/.test(amount) ? `${amount}萬` : amount;
  return `最高 ${withUnit}`;
}
